// BUG-323: 붙은 입력창([[ComposeDock]])이 자기 상태를 안쪽에 알리는 통로.
//
// 크기 손잡이([[SizeGrip]])는 평소 입력칸 **아래**에 붙는다. 그런데 팝업으로 떠 있을 때는
// 상자가 화면 바닥에 붙어 있어서, 아래 손잡이를 내려 끌어도 상자는 위로 자란다 — 손이
// 가는 방향과 자라는 방향이 반대라 불편하다(admin). 그때는 손잡이를 **위쪽**에 두고 위로
// 끌면 커지게 한다.
//
// 손잡이를 놓는 것은 부르는 쪽(댓글 폼 등)이고 그쪽은 팝업인지 모른다. 사이에 값을 끼워
// 넘기는 대신 문맥으로 알린다 — 팝업 안에 있으면 손잡이가 알아서 방향을 바꾼다.

export const COMPOSE_DOCK = Symbol('compose-dock');

export interface ComposeDockContext {
	/** 지금 팝업으로 떠 있나. */
	docked: () => boolean;
}
